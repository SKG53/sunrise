// minimal browser shims
const store: Record<string,string> = {};
(globalThis as any).window = { dispatchEvent(){}, };
(globalThis as any).localStorage = { getItem:(k:string)=>store[k]??null, setItem:(k:string,v:string)=>{store[k]=v}, removeItem:(k:string)=>{delete store[k]} };
(globalThis as any).CustomEvent = class { constructor(public t:string){} };
const S = await import("../src/lib/sale.ts");
const t = (iso:string)=>Date.parse(iso);
const ok=(c:boolean,m:string)=>{console.log((c?"PASS ":"FAIL ")+m); if(!c) process.exitCode=1};
ok(S.activeSale()?.id==="launch","launch is the sale while enabled");
ok(S.activeSale.length===0,"activeSale takes no date: nothing switches by date");
ok(!/Date\.(now|parse)/.test(S.activeSale.toString()),"activeSale never reads the clock");
ok(S.SALE_PHASES[1].enabled===false,"BF phase ships disabled");
ok(S.legacyOffersPaused()===true,"old offers stay paused while SALE_ENABLED, even between phases");
const L = S.SALE_PHASES[0];
const items=(...h:string[])=>h.map(productHandle=>({productHandle}));
ok(S.saleChannel()==="site","default channel site");
ok(JSON.stringify(S.saleCodesFor(items("30mg-peach-mango"),L))==='["SAVE30"]',"30mg only -> all code");
ok(S.saleCodesFor(items("10mg-lemonade"),L).length===0,"10mg only -> no code (10mg out of the sale Nov 25)");
ok(JSON.stringify(S.saleCodesFor(items("10mg-lemonade","60mg-blackberry-cbn"),L))==='["SAVE30"]',"mixed -> all code only");
ok(JSON.stringify(S.saleCodesFor(items("10mg-lemonade"),{...L,pctTen:60}))==='["SAVE60"]',"a phase with a 10mg deal still sends the ten code");
ok(S.saleCodesFor(items("10mg-lemonade"),{...L,pctTen:0}).length===0,"pctTen 0 -> never sends the ten code");
ok(JSON.stringify(S.saleCodesFor(items("10mg-lemonade","60mg-blackberry-cbn"),{...L,pctTen:0}))==='["SAVE30"]',"pctTen 0 + mixed -> all code only");
ok(!S.canBuyTier(10)&&S.canBuyTier(30)&&S.canBuyTier(60)&&S.NO_COUNTDOWN_TIERS.includes(10),"no Add to Cart on 10mg; no countdown on 10mg");
ok(Date.parse(S.ORDER_DEADLINE)===Date.parse("2026-12-07T05:59:59Z"),"deadline = Dec 6 11:59:59 PM CT");
ok(S.captureSaleChannel("?utm_source=brevo&utm_medium=email")&&S.saleChannel()==="brevo","utm_source=brevo -> brevo");
ok(JSON.stringify(S.saleCodesFor(items("30mg-peach-mango","10mg-strawberry"),L))==='["HOLIDAY30"]',"brevo pair (no ten code)");
ok(!S.captureSaleChannel("?utm_source=google")&&S.saleChannel()==="brevo","non-email visit keeps brevo");
ok(S.captureSaleChannel("?code=sunrise30")&&S.saleChannel()==="klaviyo","?code=sunrise30 -> klaviyo");
ok(S.captureSaleChannel("?_kx=abc")&&S.saleChannel()==="klaviyo","_kx -> klaviyo");
ok(S.captureSaleChannel("?code=HOLIDAY20")&&S.saleChannel()==="brevo","legacy HOLIDAY20 -> brevo");
ok(S.sameCodes(["save30","SAVE60"],["SAVE60","SAVE30"]),"sameCodes order/case");
ok(!S.sameCodes(["SAVE30"],["SAVE30","SAVE60"]),"sameCodes length");
ok(S.isSaleCode("bfsunrise10")&&!S.isSaleCode("SUNRISE20"),"isSaleCode");
ok(S.salePercentFor(10,L)===0&&S.salePercentFor(60,L)===30&&S.salePercentFor(10,{...L,pctTen:60})===60,"percent by tier (10mg 0)");
ok(S.saleCodesFor(items("5mg-blackberry"),L).length===0,"5mg only -> no code");
ok(JSON.stringify(S.saleCodesFor(items("5mg-blackberry","60mg-blackberry"),L))==='["HOLIDAY30"]',"5mg+60mg -> all code only (brevo channel)");
ok(S.salePercentFor(5,L)===0,"5mg 0%");
ok(S.salePrice(24.95,30)===17.47,"24.95@30 -> 17.47 (Shopify)");
ok(S.salePrice(458.95,30)===321.27,"458.95@30 -> 321.27 (Shopify)");
ok(S.salePrice(20.95,60)===8.38,"20.95@60 -> 8.38 (Shopify)");
ok(S.salePrice(28.95,30)===20.27,"28.95@30 -> 20.27");
